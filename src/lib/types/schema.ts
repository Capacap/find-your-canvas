import type { Content } from '@google/genai';

/**
 * Core data types for the creative assistant.
 *
 * Design principles:
 * - Images are always referenced by ID, never stored inline as base64.
 * - Conversations own ChatMessage records for UI display. Gemini API
 *   state (Content[] history, system prompt snapshots) lives on
 *   AgentSession records linked to the conversation. The two are
 *   populated independently and never derived from each other.
 * - All timestamps are Unix milliseconds for IndexedDB indexing.
 */

/** Top-level container. A game, a story, a visual exploration. */
export interface Project {
  id: string;
  name: string;
  description: string;
  createdAt: number;
  updatedAt: number;
}

/**
 * A conversation thread within a project.
 *
 * Chat messages (ChatMessage[]) live here for UI display. The Gemini API
 * state (tool calls, thought signatures, tool-returned thumbnails) lives
 * on the conversation's AgentSession records.
 */
export interface Conversation {
  id: string;
  projectId: string;
  title: string;
  createdAt: number;
  updatedAt: number;
}

/**
 * UI-facing record for a single chat message. Stores human-readable text
 * with [image:id] references resolved at render time. Not used for API
 * calls; see AgentSession.history for that.
 */
export interface ChatMessage {
  id: string;
  conversationId: string;
  role: 'user' | 'assistant';
  text: string;
  /** IDs of images generated or attached in this message. */
  imageIds: string[];
  /** If true, this message belongs to a turn that ended in error.
   *  The model may not have full context of these messages.
   *  Error-turn messages are deleted when the next turn begins. */
  errorTurn?: boolean;
  /** Chronological activity log from the turn that produced this message.
   *  Stored on assistant messages only; purely for UI display. */
  activityLog?: Array<{ text: string; nested: boolean }>;
  createdAt: number;
}

/** Whether an image was uploaded by the user or generated by the AI. */
export type ImageSource = 'user' | 'generated';

/** The kind of agent running in a session. */
export type AgentType = 'orchestrator' | 'text-to-image' | 'image-to-image';

/**
 * A single agent execution context. The orchestrator gets one long-lived
 * session per conversation (updated each turn). Subagent dispatches create
 * short-lived child sessions linked back via dispatchId.
 */
export interface AgentSession {
  id: string;
  conversationId: string;
  agentType: AgentType;
  /** For subagent sessions: the functionCall.id that spawned this session. */
  dispatchId?: string;
  /** Snapshot of the system prompt used for this session (or its most recent turn). */
  systemPrompt: string;
  /** Gemini Content[] for API continuity. */
  history: Content[];
  /** Length of history before the most recent successful turn.
   *  Used for rollback on orchestrator sessions. */
  preTurnHistoryLength?: number;
  createdAt: number;
  updatedAt: number;
}

/** Image metadata and thumbnail, stored separately from the full-size blob. */
export interface ImageMeta {
  id: string;
  projectId: string;
  /** The message that produced this image, if any. */
  messageId?: string;
  source: ImageSource;
  mimeType: string;
  width?: number;
  height?: number;
  /** Human-readable label assigned by the agent or user. */
  label: string;
  /** User has marked this image as especially good. */
  favorite?: boolean;
  /** The prompt or context that produced this image. */
  generationContext?: string;
  /** Downscaled JPEG (max 512px) for gallery display and model context. */
  thumbnail: Blob;
  createdAt: number;
  /** Last time this image was accessed (created, viewed, used as reference). Unix ms. */
  lastAccessedAt: number;
}

/** Full-size image blob, loaded on demand. */
export interface ImageBlob {
  id: string;
  blob: Blob;
}


/** Per-project knowledge produced and consumed by the agent. */
export interface AgentMemory {
  id: string;
  projectId: string;
  /** Agent-assigned, unique per project, e.g. "art-style". */
  slug: string;
  title: string;
  /** 1-2 sentences shown in the system prompt index. */
  summary: string;
  /** Full markdown body, fetched on demand via read_memory. */
  content: string;
  createdAt: number;
  updatedAt: number;
  /** Last time this memory was accessed (created, read, updated). Unix ms. */
  lastAccessedAt: number;
}

/** App-level settings persisted in IndexedDB. */
export interface Settings {
  id: 'app';
  geminiApiKey?: string;
}

export const DEFAULT_SETTINGS: Settings = {
  id: 'app',
  geminiApiKey: undefined
};

/** Hardcoded model IDs. Not user-configurable. */
export const TEXT_MODEL = 'gemini-3-flash-preview';
export const IMAGE_MODEL = 'gemini-3.1-flash-image-preview';
