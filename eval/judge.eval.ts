/**
 * LLM-as-judge eval pass.
 *
 * Reads traces from a completed eval run, pairs each with its
 * scenario's success criteria, and asks the text model to score
 * how well the agent performed. Verdicts are written as
 * {slug}.judge.json alongside the trace files.
 *
 * Run:  pnpm eval:judge
 * Specific run: EVAL_JUDGE_RUN=20260317T162129 pnpm eval:judge
 */
import { describe, it } from 'vitest';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { sendMessageStreaming } from '$lib/engine/gemini';
import { TEXT_MODEL } from '$lib/types/schema';
import { loadScenarios, slugify } from './scenario-loader';
import { resolveRunDir } from './run-dir';
import type { Scenario } from './scenario-loader';

const JUDGE_PROMPT = readFileSync(join(import.meta.dirname, 'judge-prompt.txt'), 'utf-8');

interface JudgeVerdict {
  scenario: string;
  score: number;
  verdict: 'pass' | 'fail';
  reasoning: string;
  judgePrompt: string;
  judgeModel: string;
  timestamp: string;
}

// ── Setup ──

const apiKey = process.env.GEMINI_API_KEY;

// Use EVAL_JUDGE_RUN to target a specific run. EVAL_RUN_ID is reserved
// for agent eval runs and auto-generated by vite.config.ts.
const runDir = resolveRunDir(process.env.EVAL_JUDGE_RUN);

const allScenarios = [
  ...loadScenarios('orchestrator'),
  ...loadScenarios('specialist')
];
const scenarioBySlug = new Map<string, Scenario>();
for (const scenario of allScenarios) {
  scenarioBySlug.set(slugify(scenario.name), scenario);
}

// Find judgeable scenarios: those with both a trace file and success criteria.
const judgeableEntries: Array<{ slug: string; scenario: Scenario }> = [];
if (runDir) {
  const traceFiles = readdirSync(runDir).filter(f => f.endsWith('.txt'));
  for (const traceFile of traceFiles) {
    const slug = traceFile.replace(/\.txt$/, '');
    const scenario = scenarioBySlug.get(slug);
    if (scenario?.successCriteria) {
      judgeableEntries.push({ slug, scenario });
    }
  }
}

// ── Tests ──

describe.skipIf(!apiKey || !runDir || judgeableEntries.length === 0)(
  'LLM judge',
  () => {
    for (const { slug, scenario } of judgeableEntries) {
      it(`judge: ${scenario.name}`, async () => {
        const traceText = readFileSync(join(runDir!, `${slug}.txt`), 'utf-8');

        const judgeInput = [
          '=== SUCCESS CRITERIA ===',
          '',
          scenario.successCriteria,
          '',
          '=== AGENT TRACE ===',
          '',
          traceText
        ].join('\n');

        const { stream, getResult } = await sendMessageStreaming(
          apiKey!,
          TEXT_MODEL,
          [{ text: judgeInput }],
          [],
          { systemInstruction: JUDGE_PROMPT }
        );

        for await (const _ of stream) { /* drain */ }

        const { text: responseText } = getResult();
        const jsonMatch = responseText.trim().match(/\{[\s\S]*\}/);
        if (!jsonMatch) {
          throw new Error(`Judge did not return valid JSON. Raw response:\n${responseText}`);
        }

        const judgeOutput = JSON.parse(jsonMatch[0]);

        if (typeof judgeOutput.score !== 'number' || judgeOutput.score < 1 || judgeOutput.score > 5) {
          throw new Error(
            `Judge returned invalid score: ${JSON.stringify(judgeOutput.score)}. ` +
            `Expected a number 1-5. Raw response:\n${responseText}`
          );
        }
        if (typeof judgeOutput.reasoning !== 'string' || judgeOutput.reasoning.length === 0) {
          throw new Error(
            `Judge returned invalid reasoning: ${JSON.stringify(judgeOutput.reasoning)}. ` +
            `Expected a non-empty string. Raw response:\n${responseText}`
          );
        }

        const verdict: JudgeVerdict = {
          scenario: scenario.name,
          score: judgeOutput.score,
          verdict: judgeOutput.score >= 3 ? 'pass' : 'fail',
          reasoning: judgeOutput.reasoning,
          judgePrompt: JUDGE_PROMPT,
          judgeModel: TEXT_MODEL,
          timestamp: new Date().toISOString()
        };

        const verdictPath = join(runDir!, `${slug}.judge.json`);
        writeFileSync(verdictPath, JSON.stringify(verdict, null, 2) + '\n', 'utf-8');

        console.log(`  ${verdict.verdict.toUpperCase()} (${verdict.score}/5): ${verdict.reasoning}`);
      });
    }
  }
);
